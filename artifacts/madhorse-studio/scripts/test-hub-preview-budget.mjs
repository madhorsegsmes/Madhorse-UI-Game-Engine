import assert from 'node:assert/strict';
import { HubPreviewQueue } from '../src/lib/hub-preview-queue.ts';
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const queue = new HubPreviewQueue();
const keys = Array.from({ length: 10 }, (_, index) => `template-${index}`);
const cleanup = keys.map(key => queue.register(key));
const active = () => keys.filter(key => queue.snapshot(key) === 'render');
assert.deepEqual(active(), [keys[0]]);
for (const key of keys) {
  assert.deepEqual(active(), [key], 'Only one template may own a live scene');
  queue.finish(key, `data:image/webp;base64,${key}`);
  assert.equal(active().length, 0, 'Wait for R3F asynchronous context disposal');
  assert.equal(queue.snapshot(key), `data:image/webp;base64,${key}`);
  await wait(800);
}
assert.equal(active().length, 0);
cleanup.forEach(dispose => dispose());
const cachedCleanup = queue.register(keys[0]);
assert.equal(active().length, 0, 'Revisiting Hub must reuse the cached image');
cachedCleanup();
const remove = queue.register('offscreen');
assert.equal(queue.snapshot('offscreen'), 'render');
remove();
assert.equal(queue.snapshot('offscreen'), 'waiting', 'Offscreen/hidden cards release their slot');
await wait(800);
const next = queue.register('visible');
assert.equal(queue.snapshot('visible'), 'render');
queue.finish('offscreen', 'late');
assert.equal(queue.snapshot('visible'), 'render', 'Late captures cannot release another scene');
next();
console.log('PASS: ten previews serialized; context-disposal delay, cached revisits, offscreen release, stale captures.');
let persisted;
const firstPage = new HubPreviewQueue([], images => { persisted = images; });
firstPage.register('fighting');
firstPage.finish('fighting', 'data:image/webp;base64,test');
const returnPage = new HubPreviewQueue(persisted);
returnPage.register('fighting');
assert.equal(returnPage.snapshot('fighting'), 'data:image/webp;base64,test', 'Restore images after full editor navigation');
console.log('PASS: serialized thumbnail cache restores without a live renderer.');
